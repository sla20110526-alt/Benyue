def validate() -> tuple[int, int]:
    total = 0
    shots = 0
    for index, scene in enumerate(SCENES, start=1):
        shot_total = sum(item[0] for item in scene["shots"])
        if shot_total != scene["duration"]:
            raise ValueError(
                f"第{index}场时长不闭合：镜头合计{shot_total}秒，场次标注{scene['duration']}秒"
            )
        for shot in scene["shots"]:
            if len(shot) != 5:
                raise ValueError(f"第{index}场存在字段数不为5的镜头：{shot!r}")
            if shot[0] <= 0:
                raise ValueError(f"第{index}场存在非正镜头时长：{shot!r}")
            if any(not str(value).strip() for value in shot[1:]):
                raise ValueError(f"第{index}场存在空字段：{shot!r}")
        total += scene["duration"]
        shots += len(scene["shots"])
    if total != TARGET_SECONDS:
        raise ValueError(f"全片建议素材时长不闭合：{total}秒 != {TARGET_SECONDS}秒")
    return total, shots


