def validate():
    total = 0
    shots = 0
    for index, scene in enumerate(SCENES, start=1):
        actual = sum(s[0] for s in scene["shots"])
        if actual != scene["duration"]:
            raise ValueError(f"第{index}场时长错误：声明{scene['duration']}，逐镜合计{actual}")
        total += actual
        shots += len(scene["shots"])
    if total != TARGET_SECONDS:
        raise ValueError(f"全片时长错误：{total}")
    return total, shots
